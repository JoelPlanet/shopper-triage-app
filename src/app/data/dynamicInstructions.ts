const normalizedInstructions = dynamicInstructions.map((entry) => ({
  ...entry,
  airport: entry.airport.trim(),
  countryCode: entry.countryCode.trim().toUpperCase(),
}));

export function normalizeCountryCode(countryCode: string | null | undefined): string {
  if (!countryCode) {
    return "";
  }

  const resolved = countryCode.trim().toUpperCase();

  return resolved === "FL" ? "FI" : resolved;
}

export function getDynamicInstruction(countryCode: string | null | undefined, airport: string | null | undefined): DynamicInstructionEntry | null {
  const resolvedCountryCode = normalizeCountryCode(countryCode);
  const resolvedAirport = (airport ?? "").trim();

  if (!resolvedCountryCode) {
    return null;
  }

  const exactMatch = normalizedInstructions.find((entry) => entry.countryCode === resolvedCountryCode && entry.airport === resolvedAirport);

  if (exactMatch) {
    return exactMatch;
  }

  const otherMatch = normalizedInstructions.find((entry) => entry.countryCode === resolvedCountryCode && entry.airport === "Other");

  if (otherMatch) {
    return otherMatch;
  }

  return normalizedInstructions.find((entry) => entry.countryCode === resolvedCountryCode) ?? null;
}

export function getInstructionAssetUrl(country: string, fileName: string): string {
  return encodeURI(`/Spec Assets/Digital Concierge Assets/${country}/${fileName}`);
}
